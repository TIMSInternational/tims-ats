using Tims.Application.InterviewTranscription;

namespace Tims.UnitTests.InterviewTranscription;

public sealed class WebVttTranscriptTests
{
    private static readonly IReadOnlyList<TranscriptionStaffName> Staff =
        [new(Guid.NewGuid(), "Laura", "Mora"), new(Guid.NewGuid(), "Diego", "Solís")];

    [Fact]
    public void Voice_tags_become_roles_and_no_name_survives()
    {
        const string vtt = """
            WEBVTT

            NOTE generated by the provider

            1
            00:00:01.000 --> 00:00:04.000
            <v Laura Mora>Buenos días, ¿cómo está?</v>

            2
            00:00:05.250 --> 00:00:09.000
            <v Ana Pérez>Muy bien, gracias por la invitación.</v>

            3
            00:01:10.000 --> 00:01:15.000
            <v.loud Diego Solís>Cuénteme de su último proyecto.</v>
            """;
        var parsed = WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff);
        Assert.False(parsed.Truncated);
        Assert.Equal(
            [(1, "interviewer_1", "Buenos días, ¿cómo está?"), (5, "candidate", "Muy bien, gracias por la invitación."),
             (70, "interviewer_2", "Cuénteme de su último proyecto.")],
            parsed.Segments.Select(s => (s.StartSeconds, s.Speaker, s.Text)).ToArray());
        Assert.DoesNotContain(parsed.Segments, s => s.Speaker.Contains("Laura") || s.Speaker.Contains("Ana"));
    }

    [Fact]
    public void Matching_is_case_and_space_insensitive_and_uses_the_join_display_name()
    {
        const string vtt = "WEBVTT\n\n00:00:02.000 --> 00:00:03.000\n<v  ana   PÉREZ >Hola</v>\n";
        Assert.Equal("candidate", Assert.Single(WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff).Segments).Speaker);
    }

    [Fact]
    public void A_leading_name_colon_is_a_speaker_only_for_a_known_participant()
    {
        const string vtt = """
            WEBVTT

            00:00:01.000 --> 00:00:02.000
            Laura Mora: ¿Qué hizo en ese rol?

            00:00:03.000 --> 00:00:05.000
            Nota: lideré un equipo de cinco personas.
            """;
        var parsed = WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff);
        Assert.Equal(("interviewer_1", "¿Qué hizo en ese rol?"), (parsed.Segments[0].Speaker, parsed.Segments[0].Text));
        Assert.Equal(("unknown", "Nota: lideré un equipo de cinco personas."),
            (parsed.Segments[1].Speaker, parsed.Segments[1].Text));
    }

    [Fact]
    public void Unknown_named_speakers_are_numbered_participants()
    {
        const string vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n<v Observador Externo>Hola</v>\n\n" +
                           "00:00:03.000 --> 00:00:04.000\n<v Otra Persona>Buenas</v>\n";
        Assert.Equal(["participant_1", "participant_2"],
            WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff).Segments.Select(s => s.Speaker).ToArray());
    }

    [Fact]
    public void Consecutive_cues_of_one_speaker_merge_keeping_the_first_timestamp()
    {
        const string vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n<v Ana Pérez>Primero</v>\n\n" +
                           "00:00:02.500 --> 00:00:03.000\n<v Ana Pérez>segundo</v>\n\n" +
                           "00:00:04.000 --> 00:00:05.000\n<v Laura Mora>Gracias</v>\n";
        var segments = WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff).Segments;
        Assert.Equal(2, segments.Count);
        Assert.Equal((1, "Primero segundo"), (segments[0].StartSeconds, segments[0].Text));
    }

    [Fact]
    public void Markup_entities_and_control_characters_are_cleaned_and_hours_are_read()
    {
        const string vtt = "WEBVTT\r\n\r\n01:02:03.000 --> 01:02:04.000\r\n<v Ana Pérez><i>Uso</i> C&amp;C ​\u0007ok</v>\r\n";
        var segment = Assert.Single(WebVttTranscript.Parse(vtt, "Ana", "Pérez", Staff).Segments);
        Assert.Equal((3723, "Uso C&C ok"), (segment.StartSeconds, segment.Text));
    }

    [Fact]
    public void Empty_or_cue_less_input_yields_nothing()
    {
        Assert.Empty(WebVttTranscript.Parse(null, "Ana", "Pérez", Staff).Segments);
        Assert.Empty(WebVttTranscript.Parse("WEBVTT\n\nNOTE only\n", "Ana", "Pérez", Staff).Segments);
    }

    [Fact]
    public void Output_is_bounded_and_flags_truncation()
    {
        var cues = string.Concat(Enumerable.Range(0, WebVttTranscript.MaxSegments + 10).Select(i =>
            $"\n\n00:{i / 60 % 60:00}:{i % 60:00}.000 --> 00:00:00.000\n<v {(i % 2 == 0 ? "Ana Pérez" : "Laura Mora")}>texto {i}</v>"));
        var parsed = WebVttTranscript.Parse("WEBVTT" + cues, "Ana", "Pérez", Staff);
        Assert.True(parsed.Truncated);
        Assert.Equal(WebVttTranscript.MaxSegments, parsed.Segments.Count);

        var huge = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n<v Ana Pérez>" + new string('a', 5_000) + "</v>\n";
        Assert.Equal(WebVttTranscript.MaxSegmentChars,
            Assert.Single(WebVttTranscript.Parse(huge, "Ana", "Pérez", Staff).Segments).Text.Length);
    }
}
