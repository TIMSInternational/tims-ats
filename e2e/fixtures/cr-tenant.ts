export type CrTenantIdKey = keyof typeof ID_VALUES;

// Values are typed `string` (not literal) so callers can test arbitrary strings against them.
export const CR_TENANT_IDS: Readonly<Record<CrTenantIdKey, string>> = Object.freeze(ID_VALUES);

export type CrBusinessUnitKey = 'vivienda' | 'administrativa';
export type CrTeamKey = 'proyectos' | 'comite';
export type CrUserKey =
  | 'superAdmin'
  | 'hrAdmin'
  | 'recruiter'
  | 'hrbpUnit'
  | 'hrbpNoUnit'
  | 'leader'
  | 'committee'
  | 'employee'
  | 'orgAdminDeny';

export interface CrBusinessUnit {
  readonly id: string;
  readonly name: string;
  readonly code: string;
}

export interface CrTeam {
  readonly id: string;
  readonly name: string;
  readonly businessUnit: CrBusinessUnitKey;
  readonly leader: CrUserKey | null;
}

export interface CrUser {
  readonly id: string;
  readonly email: string;
  readonly firstName: string;
  readonly lastName: string;
  /** A SYSTEM_ROLE_CATALOG slug, or null for the deny-proof persona with no grants. */
  readonly roleSlug: string | null;
  readonly locale: 'es';
  readonly timezone: 'America/Costa_Rica';
  readonly businessUnits: readonly CrBusinessUnitKey[];
  readonly teams: readonly CrTeamKey[];
}

export interface CrVacancy {
  readonly id: string;
  readonly title: string;
  readonly status: 'published' | 'pending_approval' | 'draft';
  /** Monthly CRC salary band, or null when the seed leaves it unset. */
  readonly salaryMin: number | null;
  readonly salaryMax: number | null;
}

const TZ = 'America/Costa_Rica' as const;
const DOMAIN = 'vivienda-e2e.test';

function user(
  id: string,
  local: string,
  firstName: string,
  lastName: string,
  roleSlug: string | null,
  businessUnits: readonly CrBusinessUnitKey[] = [],
  teams: readonly CrTeamKey[] = [],
): CrUser {
  return {
    id,
    email: `${local}@${DOMAIN}`,
    firstName,
    lastName,
    roleSlug,
    locale: 'es',
    timezone: TZ,
    businessUnits,
    teams,
  };
}

